"""
Writes labeled training examples in standard YOLO format, generated by the
TV Royale auto-labeling pipeline — see data/tv_royale_watcher.py for the
live orchestration (the "macro"), and Project_Status /
clash-royale-ai-pipeline-explained.md section 5 for the full design this is
one piece of.

Two independent halves, split deliberately so the first is usable and
testable right now:

1. YoloDatasetWriter — pure dataset formatting/bookkeeping. Feed it
   (image, [(class_name, bbox), ...]) from anywhere — synthetic examples
   (see data/test_auto_labeler.py), a saved screenshot, or eventually the
   live pipeline — and it writes correctly-formatted YOLO examples. No
   live TV Royale access needed.

   Side (ally/enemy) is deliberately NOT part of the class taxonomy here
   — corrected 2026-08-16, before any real data was collected, after
   Duncan's own catch: an isolated unit crop mostly doesn't carry a
   stable per-sprite team signal (Clash Royale doesn't skin-tint troops by
   side), so baking "giant_ally"/"giant_enemy" into what the detector
   predicts per-crop would have quietly retrained the same architectural
   mistake as side.onnx, just at a larger scale — the actual team signal
   (the color-coded level number / health bar, and, failing that, board
   context + track persistence) lives elsewhere and doesn't belong in a
   per-crop class label. The detector trained on this data predicts CLASS
   ONLY; side is determined by a separate mechanism (see the planned
   perception/side_reader.py, and the own-play-certainty + track-
   persistence fallback for the one case with no visual signal at all —
   a full-health, undamaged ally troop).

2. localize_play() — the live-pipeline glue: given a detected play (from
   two game_knowledge.cycle_tracker.CycleTracker instances watching TV
   Royale's dual hand layout) and this frame's newly-appeared tracks (from
   perception/unit_tracker.py, already running for live play), finds a
   bounding box for it, falling back to perception/frame_diff.py only when
   no track corresponds to the play at all. Written now, genuinely can't
   be INTEGRATION-tested yet (needs config/tv_royale_regions.py, which
   needs a live calibration session — see the plan) — kept here anyway so
   the whole pipeline exists as real code the moment calibration is done,
   rather than being written from scratch then.

Output layout — the standard format ultralytics/YOLO training expects
directly, no conversion step needed later:
    data/unit_training/
        images/<id>.jpg
        labels/<id>.txt      -- one line per object: "class_id cx cy w h",
                                 all normalized 0-1 relative to image size
        classes.txt           -- one class name per line, index = class_id
"""

import os

import cv2

from perception import frame_diff
from perception.unit_detector import CLASS_NAMES

OUTPUT_DIR = "data/unit_training"  # default output_dir for YoloDatasetWriter;
# images/, labels/, classes.txt live under here — see that class's docstring.

MAX_EXAMPLES_PER_CLASS = 2000  # far higher than auto_collect.py's
# MAX_EXAMPLES_PER_CARD=40 -- that caps template-matching examples, a much
# smaller/simpler need (a handful of examples is enough to match against).
# A detector benefits from real volume, but an unattended macro run over
# many hours still needs SOME ceiling so a common class (e.g. Knight)
# doesn't quietly consume all the disk space before rarer classes get any
# real representation. First-pass number, not tuned against real
# class-frequency data yet.

# Class-only taxonomy -- side is deliberately excluded, see module
# docstring's "Side (ally/enemy)" note above for why.
CLASS_LIST = list(CLASS_NAMES)
CLASS_INDEX = {name: i for i, name in enumerate(CLASS_LIST)}

NEW_TRACK_WINDOW_SECONDS = 2.0  # how long after a detected play a newly-
# appeared track (from perception.unit_tracker) is still eligible to be
# treated as that play's unit. Generous first-pass value, not yet tuned
# against real TV Royale footage — no such footage exists yet to tune
# against (see module docstring).


def _ensure_dirs(images_dir, labels_dir, classes_file):
    os.makedirs(images_dir, exist_ok=True)
    os.makedirs(labels_dir, exist_ok=True)
    if not os.path.isfile(classes_file):
        with open(classes_file, "w", encoding="utf-8") as f:
            f.write("\n".join(CLASS_LIST) + "\n")


class YoloDatasetWriter:
    """Tracks per-class example counts (enforcing MAX_EXAMPLES_PER_CLASS)
    across a whole run — construct once, call write() per labeled example.
    Counts are seeded from whatever's already on disk, so resuming an
    interrupted collection run doesn't reset the caps or overwrite
    existing files. output_dir defaults to the real dataset location
    (OUTPUT_DIR) but is overridable — used by data/test_auto_labeler.py so
    synthetic tests don't read/write the real collected dataset."""

    def __init__(self, output_dir: str = OUTPUT_DIR):
        self.images_dir = os.path.join(output_dir, "images")
        self.labels_dir = os.path.join(output_dir, "labels")
        self.classes_file = os.path.join(output_dir, "classes.txt")
        _ensure_dirs(self.images_dir, self.labels_dir, self.classes_file)
        self._next_id = self._count_existing_images()
        self._class_counts = self._count_existing_labels()

    def _count_existing_images(self) -> int:
        return len([f for f in os.listdir(self.images_dir) if f.endswith(".jpg")])

    def _count_existing_labels(self) -> dict:
        counts = {name: 0 for name in CLASS_LIST}
        for fname in os.listdir(self.labels_dir):
            if not fname.endswith(".txt"):
                continue
            with open(os.path.join(self.labels_dir, fname), encoding="utf-8") as f:
                for line in f:
                    if not line.strip():
                        continue
                    class_id = int(line.split()[0])
                    counts[CLASS_LIST[class_id]] += 1
        return counts

    def at_cap(self, class_name: str) -> bool:
        return self._class_counts.get(class_name, 0) >= MAX_EXAMPLES_PER_CLASS

    def write(self, image_bgr, objects: list):
        """objects: list of (class_name, (x1, y1, x2, y2)) in this image's
        own pixel coordinates -- no side field, see module docstring's
        "Side (ally/enemy)" note. Writes the image + one YOLO label line
        per object whose class isn't already at MAX_EXAMPLES_PER_CLASS —
        an object AT cap is silently skipped rather than skipping the
        whole image, so a frame with one over-represented unit and one
        rare one still contributes the rare one. Returns the example's id
        (stem of the written filename), or None if every object in this
        frame was skipped (including the case where objects is empty)."""
        h, w = image_bgr.shape[:2]
        lines = []
        counted = []
        for class_name, (x1, y1, x2, y2) in objects:
            if self.at_cap(class_name):
                continue
            class_id = CLASS_INDEX[class_name]
            cx = (x1 + x2) / 2 / w
            cy = (y1 + y2) / 2 / h
            bw = (x2 - x1) / w
            bh = (y2 - y1) / h
            lines.append(f"{class_id} {cx:.6f} {cy:.6f} {bw:.6f} {bh:.6f}")
            counted.append(class_name)

        if not lines:
            return None

        example_id = f"{self._next_id:07d}"
        self._next_id += 1
        cv2.imwrite(os.path.join(self.images_dir, f"{example_id}.jpg"), image_bgr)
        with open(os.path.join(self.labels_dir, f"{example_id}.txt"), "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
        for class_name in counted:
            self._class_counts[class_name] = self._class_counts.get(class_name, 0) + 1
        return example_id


def localize_play(new_tracks: list, before_crop=None, after_crop=None):
    """Finds a bounding box for a detected play. new_tracks: tracks that
    newly appeared since the play (from perception.unit_tracker's
    current_state(), already filtered by the caller to roughly
    NEW_TRACK_WINDOW_SECONDS) — this function deliberately ignores
    whatever class/side those tracks were guessed as; the caller already
    knows the true class/side from the authoritative dual-hand-tracking
    signal and only needs a BOX from here.

    Primary path: whichever of new_tracks has the HIGHEST age (confirmed-
    frame count) — same "prefer the most established candidate" reasoning
    as opponent_play_tracker.py's PLAY_PERSISTENCE_MIN_AGE gate, since a
    track that's stayed confirmed longer is less likely to be noise than
    a barely-confirmed one, when several new_tracks are plausible
    candidates for the same play. Fallback: perception.frame_diff against
    before/after arena crops, only when new_tracks is empty — i.e. only
    for a genuine detection miss.

    Returns a (x1, y1, x2, y2) bbox, or None if nothing plausible was
    found either way."""
    if new_tracks:
        newest = max(new_tracks, key=lambda t: t["age"])
        return newest["bbox"]
    if before_crop is not None and after_crop is not None:
        blobs = frame_diff.find_new_blobs(before_crop, after_crop)
        if blobs:
            # No calibrated expected-position prior yet (needs
            # config/tv_royale_regions.py, not built — see module
            # docstring) -- take the largest blob as the best guess.
            # Revisit once real geometry (e.g. "near this side's own
            # bridge") is available to pick among several candidates.
            return max(blobs, key=lambda b: (b[2] - b[0]) * (b[3] - b[1]))
    return None
